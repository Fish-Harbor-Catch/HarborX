const LanguageContext = createContext({
  lang: "en",
  setLang: () => {},
  t: (key, fallback, params) => fallback || key,
});

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try {
      return localStorage.getItem("harborx_lang") || "en";
    } catch {
      return "en";
    }
  });

  const setLang = (newLang) => {
    setLangState(newLang);
    try {
      localStorage.setItem("harborx_lang", newLang);
    } catch {}
  };

  const t = (key, fallback, params) => {
    const langDict = TRANSLATIONS[lang] || TRANSLATIONS.en;
    let res = langDict[key] ?? TRANSLATIONS.en[key] ?? (fallback !== undefined ? fallback : key);
    if (params && typeof res === "string") {
      Object.entries(params).forEach(([k, v]) => {
        res = res.replaceAll(`{${k}}`, v);
      });
    }
    return res;
  };

  return (
    <LanguageContext.Provider value={{ lang, setLang, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  return useContext(LanguageContext);
}

/**
 * Compact Dropdown Language Selector Component.
 * - Displays active code (default "EN") with dropdown chevron.
 * - On click, displays compact dropdown directly below.
 * - Options: 1. English (EN), 2. தமிழ் (TA), 3. සිංහල (SI).
 * - Highlights selected language with checkmark.
 * - Closes on selection, click outside, or Escape.
 */
export function LanguageSwitcher({ className = "" }) {
  const { lang, setLang } = useLanguage();
  const [isOpen, setIsOpen] = useState(false);
  const containerRef = useRef(null);
  const triggerRef = useRef(null);

  // Close when clicking outside
  useEffect(() => {
    if (!isOpen) return;
    const handleClickOutside = (e) => {
      if (containerRef.current && !containerRef.current.contains(e.target)) {
        setIsOpen(false);
      }
    };
    document.addEventListener("mousedown", handleClickOutside);
    document.addEventListener("touchstart", handleClickOutside);
    return () => {
      document.removeEventListener("mousedown", handleClickOutside);
      document.removeEventListener("touchstart", handleClickOutside);
    };
  }, [isOpen]);

  // Handle keyboard navigation: Escape closes dropdown
  useEffect(() => {
    if (!isOpen) return;
    const handleKeyDown = (e) => {
      if (e.key === "Escape") {
        setIsOpen(false);
        triggerRef.current?.focus();
      }
    };
    document.addEventListener("keydown", handleKeyDown);
    return () => document.removeEventListener("keydown", handleKeyDown);
  }, [isOpen]);

  const handleSelect = (code) => {
    setLang(code);
    setIsOpen(false);
    triggerRef.current?.focus();
  };

  const currentCode = (lang || "en").toUpperCase();

  return (
    <div
      ref={containerRef}
      className={`lang-selector-wrap lang-switcher ${className}`.trim()}
    >
      <button
        ref={triggerRef}
        type="button"
        className={`lang-selector-trigger ${isOpen ? "open" : ""}`}
        onClick={() => setIsOpen((prev) => !prev)}
        aria-haspopup="listbox"
        aria-expanded={isOpen}
        aria-label="Select display language"
        title="Select display language"
      >
        <span className="lang-code">{currentCode}</span>
        <ChevronDown
          size={14}
          className={`lang-chevron ${isOpen ? "rotated" : ""}`}
          aria-hidden="true"
        />
      </button>

      {isOpen && (
        <div
          className="lang-dropdown-menu"
          role="listbox"
          aria-label="Display languages"
        >
          {LANGUAGES.map((item) => {
            const isSelected = lang === item.code;
            return (
              <button
                key={item.code}
                type="button"
                role="option"
                aria-selected={isSelected}
                className={`lang-dropdown-item ${isSelected ? "selected" : ""}`}
                onClick={() => handleSelect(item.code)}
              >
                <span className="lang-item-label">{item.label}</span>
                {isSelected && (
                  <Check
                    size={14}
                    className="lang-item-check"
                    aria-hidden="true"
                  />
                )}
              </button>
            );
          })}
        </div>
      )}
    </div>
  );
}

// Backward-compatibility alias
export const LanguageSelector = LanguageSwitcher;
